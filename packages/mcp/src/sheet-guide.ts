/**
 * **検証シートの書き方を、エージェントへ渡す**（2026-09-24・人の指示）。
 *
 * > 検証シート作成ノウハウは MCP などでエージェントに共有できる仕組みにしてください
 *
 * **同じ日に、同じ相手が 3 回、雑なシートを書いた。**ノウハウが**どこにも無かった**ため。
 * **文書に書くだけでは、次のエージェントが読まない。****口から渡す。**
 *
 * **文書（`docs/sheet-writing.md`）を正本にして読み出す。**
 * ここに中身を書くと、**文書と実装がずれる**（`product-baseline.md` §10）。
 */

/**
 * 読めた文書をそのまま返す。**読めなければ、読めないと言う**（C20）。
 *
 * **黙って空で返さない。**空を返すと、聞いた側は「ノウハウは無い」と受け取る。
 * **読めなくても、いちばん効く 1 つだけは渡す** —— それが無いと、雑なシートが通る。
 */
export function sheetGuideOr(markdown: string | undefined): string {
  if (markdown !== undefined && markdown.trim() !== '') return markdown;

  return [
    '**検証シートの書き方の文書（docs/sheet-writing.md）を読めなかった。**',
    '',
    'いちばん大事な 1 つだけ、ここに書く。',
    '',
    '> **期待結果に、押す前から画面に在る文字を書かない。**',
    '',
    'この道具の期待結果は `「X」と表示される` だけで、**在るか、しか見ない。**',
    '**押す前から在る文字を書くと、何も起きなくても通る。**',
    '書く前に「押す前にこの文字は画面に在るか？」と自分に聞くこと。',
  ].join('\n');
}
