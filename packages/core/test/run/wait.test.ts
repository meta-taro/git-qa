import { describe, expect, it } from 'vitest';

import { WAIT_KEY, rowWait, sheetWaitMs } from '../../src/run/wait.js';

/**
 * **待ち時間がシートから変えられなかった**（外部レビュー meta-taro/git-qa#39）。
 *
 * > **製品は正常なのに FAIL が出ます。**
 * > キャプチャを見たら、入力も押下も成功していました。…
 * > つまり落ちたのは**アプリの不具合ではなく、待ち切る前に見切ったから**です。
 *
 * 既定は 2 秒。**開いて読むだけのページなら足りる。**
 * **押すとサーバを 1 往復する行**（ログイン → リダイレクト、採番してから遷移）では足りない。
 *
 * **CLI の引数にはしない**（報告者の提案 3 —— 報告者自身が薦めていない）。
 *
 * > 実行のたびに変わる値がシートの外にあると、`run.json` を読んだ人が
 * > 「この FAIL は待ち不足か、製品の問題か」を判断できなくなります
 *
 * **シートに書けば、証跡の `sha256` から後で復元できる。**`#22` と同じ理由。
 */
describe('sheetWaitMs', () => {
  it('書いていなければ undefined（既定のまま）', () => {
    expect(sheetWaitMs({})).toBeUndefined();
    expect(sheetWaitMs({ [WAIT_KEY]: '   ' })).toBeUndefined();
  });

  it('秒で書ける', () => {
    expect(sheetWaitMs({ [WAIT_KEY]: '8s' })).toBe(8000);
    expect(sheetWaitMs({ [WAIT_KEY]: '8 s' })).toBe(8000);
    expect(sheetWaitMs({ [WAIT_KEY]: '8秒' })).toBe(8000);
  });

  it('小数の秒も読む（0.5s）', () => {
    expect(sheetWaitMs({ [WAIT_KEY]: '0.5s' })).toBe(500);
  });

  it('ミリ秒でも書ける', () => {
    expect(sheetWaitMs({ [WAIT_KEY]: '8000ms' })).toBe(8000);
  });

  it('単位が無ければ秒として読む（人は秒で考える）', () => {
    expect(sheetWaitMs({ [WAIT_KEY]: '8' })).toBe(8000);
  });

  /**
   * **読めないものは黙って既定にしない**（C20）。
   * 「8 秒待つつもりで書いたのに 2 秒だった」が、**いちばん気づけない。**
   */
  it('読めない書き方は投げる（黙って既定に落とさない）', () => {
    expect(() => sheetWaitMs({ [WAIT_KEY]: 'ながめ' })).toThrow(/待つ/);
    expect(() => sheetWaitMs({ [WAIT_KEY]: '-3s' })).toThrow(/待つ/);
    expect(() => sheetWaitMs({ [WAIT_KEY]: '0' })).toThrow(/待つ/);
  });

  /**
   * **上限を持つ。**打ち間違い（`800s`）で**実行が 1 件 13 分**になると、
   * 人は止めるしかなくなり、証跡が中断で残る。
   */
  it('長すぎるものは投げる（打ち間違いで実行が止まらなくなる）', () => {
    expect(() => sheetWaitMs({ [WAIT_KEY]: '800s' })).toThrow(/待つ/);
  });

  it('上限ちょうどは通る', () => {
    expect(sheetWaitMs({ [WAIT_KEY]: '120s' })).toBe(120_000);
  });
});

/**
 * **遅い行だけ延ばす**（外部レビュー meta-taro/git-qa#39 の提案 2・2026-10-23）。
 *
 * 相手先のサイトを人の速さ（1 ページ 4〜7 秒）で回るアプリでは、
 * 結果が出るまで**数分**かかる。見出しの `# 待つ:`（上限 120 秒）では足りず、
 * **全体を延ばすと、落ちる行がみな数分ずつ遅くなる。**
 *
 * **期待結果の欄に、その行だけの待ちを添える。**シートに書くので、
 * 証跡の `sha256` から「何秒待った行か」を後で復元できる（#22 と同じ理由）。
 */
describe('rowWait', () => {
  it('添えていなければ、文はそのまま・待ちは無し', () => {
    expect(rowWait('「保存しました」と表示される')).toEqual({
      text: '「保存しました」と表示される',
    });
  });

  it('（最大 5 分）を読み、文から外す', () => {
    expect(rowWait('「反映しました」と表示される（最大 5 分）')).toEqual({
      text: '「反映しました」と表示される',
      waitMs: 300_000,
    });
  });

  it('（15秒まで待つ）も読む', () => {
    expect(rowWait('「ラウンド 2」と表示される（15秒まで待つ）')).toEqual({
      text: '「ラウンド 2」と表示される',
      waitMs: 15_000,
    });
  });

  it('半角の括弧・s / min でも読む', () => {
    expect(rowWait('「済」と表示される (最大 90s)').waitMs).toBe(90_000);
    expect(rowWait('「済」と表示される（最大 3min）').waitMs).toBe(180_000);
    expect(rowWait('「済」と表示される（最大 1.5 分）').waitMs).toBe(90_000);
  });

  /** **待ちの言い方ではない括弧には触らない。**人が読む但し書きはよくある。 */
  it('待ちではない括弧は、そのまま残す', () => {
    expect(rowWait('「保存」と表示される（右上）')).toEqual({
      text: '「保存」と表示される（右上）',
    });
    // **「最大」でも、時間でなければ待ちではない**（件数の但し書きはよくある）。
    expect(rowWait('「履歴」と表示される（最大 10 件）')).toEqual({
      text: '「履歴」と表示される（最大 10 件）',
    });
  });

  /**
   * **読めないものは黙って既定にしない**（C20）。
   * 「5 分待つつもりで書いたのに 2 秒だった」が、**いちばん気づけない。**
   */
  it('待ちの言い方なのに読めなければ投げる', () => {
    expect(() => rowWait('「済」と表示される（しばらくまで待つ）')).toThrow(/待つ/);
    expect(() => rowWait('「済」と表示される（最大 2 時間）')).toThrow(/待つ/);
    expect(() => rowWait('「済」と表示される（5時間まで待つ）')).toThrow(/待つ/);
    expect(() => rowWait('「済」と表示される（最大 0 秒）')).toThrow(/待つ/);
  });

  it('2 つ添えてあれば投げる（どちらを守るか決められない）', () => {
    expect(() => rowWait('「済」と表示される（最大 1 分）（最大 2 分）')).toThrow(/待つ/);
  });

  /**
   * **上限は 10 分。**行ごとなので見出し（120 秒）より長くてよいが、
   * 打ち間違い（`50 分`）で人が止めるしかなくなる実行は作らない。
   */
  it('10 分を超えれば投げる・10 分ちょうどは通る', () => {
    expect(() => rowWait('「済」と表示される（最大 11 分）')).toThrow(/待つ/);
    expect(rowWait('「済」と表示される（最大 10 分）').waitMs).toBe(600_000);
  });
});
